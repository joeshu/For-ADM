import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
import {readJSON} from './lib/ad-sites.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const manifest=readJSON(path.join(root,'universal/templates.json'));
const registered=[...manifest.templates,...(manifest.requestRules||[]).map(r=>({...r,bindings:[{domains:r.domains}]}))];
const registry=readJSON(path.join(root,'universal/sites.json'));
assert.equal(registry.schemaVersion,1);
const ids=new Set(),covered=new Set();
for(const site of registry.sites){
 assert(/^[a-z0-9][a-z0-9-]*$/.test(site.id)&&!ids.has(site.id),'Invalid/duplicate site ID');ids.add(site.id);
 assert(['source-verified','device-verified','pending'].includes(site.status),'Invalid site status');
 for(const url of [...site.releasePages,...site.testUrls])assert(['https:','http:'].includes(new URL(url).protocol),'Invalid site URL');
 if(site.status==='pending'){assert.equal(site.template,null,'Pending site must not enable a template');continue;}
 assert(registered.some(t=>t.id===site.template),'Missing template');covered.add(site.template);
}
for(const template of registered)assert(covered.has(template.id),'Template is missing from site registry: '+template.id);
const safe=s=>String(s).replaceAll('|','\\|').replace(/[\r\n]/g,' ');
function hosts(template){return template.bindings.map(b=>{
 const d=b.domains;
 const base=d.type==='exact'?d.names.join(', '):d.type==='numbered'?'('+d.brands.join('|')+')数字.'+d.tld:d.prefix+'.['+d.suffixes.join(', ')+']';
 return base+(d.prefixes?.some(Boolean)?'；前缀：'+d.prefixes.map(p=>p||'无').join('/'):'');
}).join('；');}
const rows=registry.sites.map(site=>{
 const template=registered.find(t=>t.id===site.template);
 return '| '+[site.name,site.status,site.template||'未启用',template?hosts(template):'无',site.releasePages.join(' '),site.testUrls.join(' '),site.notes].map(safe).join(' | ')+' |';
});
const content='# 网站登记表\n\n<!-- GENERATED by scripts/site-registry.mjs; do not edit. -->\n\n域名与路径以 templates.json 为唯一运行时来源。此表仅记录来源与核验状态，不自动扩大匹配。source-verified 表示已核验源码，device-verified 才表示已完成设备测试；测试链接不是当前可访问性承诺。pending 不进入重写或 MITM。\n\n| 网站 | 状态 | 模板 | 正式域名边界 | 发布页 | 测试链接 | 说明 |\n| --- | --- | --- | --- | --- | --- | --- |\n'+rows.join('\n')+'\n';
const dest=path.join(root,'universal/SITES.md');
if(process.argv.includes('--check'))assert(fs.existsSync(dest)&&fs.readFileSync(dest,'utf8')===content,'Stale SITES.md; run node scripts/site-registry.mjs');
else fs.writeFileSync(dest,content);
console.log('Site registry verified: '+covered.size+' active entries; pending entries excluded');
